"""Run with python -m scripts.data; normal builds remain entirely offline."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from .fetch import fetch
from .reconcile import changes, digest, encode, reconcile, verify
from .sources import SOURCES


def main() -> int:
    """Dispatch explicit offline verification/reconciliation or staged fetches."""
    parser = argparse.ArgumentParser(description=__doc__)
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument(
        "--verify",
        action="store_true",
        help="verify pinned hashes and exact generated bytes without network",
    )
    action.add_argument(
        "--reconcile",
        action="store_true",
        help="derive inventory/research artifacts from local raw inputs",
    )
    action.add_argument(
        "--fetch",
        metavar="STAGING_DIRECTORY",
        type=Path,
        help="fetch into a new directory, without replacing approved snapshots",
    )
    action.add_argument(
        "--diff",
        metavar="PREVIOUS_ROOT",
        type=Path,
        help="compare verified previous/current dataset roots",
    )
    parser.add_argument(
        "--root", type=Path, default=Path(__file__).resolve().parents[2]
    )
    parser.add_argument(
        "--evaluation-date", help="explicit YYYY-MM-DD policy evaluation date"
    )
    parser.add_argument(
        "--retrieved-on",
        help="explicit YYYY-MM-DD retrieval date for changed snapshots",
    )
    parser.add_argument(
        "--report", type=Path, help="write a deterministic diff JSON file"
    )
    parser.add_argument("--timeout", type=float, default=20)
    parser.add_argument("--max-bytes", type=int, default=5_000_000)
    args = parser.parse_args()
    try:
        if args.verify:
            record = verify(args.root)
            print("Verified " + record["dataset_version"])
        elif args.diff:
            result = changes(args.diff, args.root)
            if args.report:
                args.report.write_bytes(encode(result))
            else:
                sys.stdout.buffer.write(encode(result))
        else:
            existing_path = args.root / "data/manifest.json"
            existing = (
                json.loads(existing_path.read_text(encoding="utf-8"))
                if existing_path.exists()
                else {}
            )
            if (args.fetch or not existing) and (
                not args.evaluation_date or not args.retrieved_on
            ):
                parser.error(
                    "--evaluation-date and --retrieved-on are required for a new dataset"
                )
            if args.reconcile and existing and not args.retrieved_on:
                old_hashes = {
                    x["source_id"]: x["sha256"] for x in existing.get("inputs", [])
                }
                if any(
                    old_hashes.get(source) != digest((args.root / path).read_bytes())
                    for source, (path, _) in SOURCES.items()
                ):
                    parser.error(
                        "--retrieved-on is required when raw source bytes change"
                    )
            evaluation_date = args.evaluation_date or existing.get("evaluation_date")
            retrieved_on = args.retrieved_on or evaluation_date
            if not evaluation_date or not retrieved_on:
                parser.error(
                    "--evaluation-date and --retrieved-on are required for a new dataset"
                )
            if args.fetch:
                record = fetch(
                    args.fetch,
                    evaluation_date,
                    retrieved_on,
                    timeout=args.timeout,
                    max_bytes=args.max_bytes,
                )
            else:
                record = reconcile(args.root, evaluation_date, retrieved_on)
            print("Prepared " + record["dataset_version"])
    except (ValueError, KeyError, OSError) as exc:
        print("Inventory error: " + str(exc), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
